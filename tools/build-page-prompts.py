#!/usr/bin/env python3
"""Turns the storyboard pages 11 and up (story-bible/chapter-1/pages-*.md) into image prompt blocks and writes them
into art/prompts/ch1-pages-all-with-dialogue.md, after page 10. Pages that still say TO BE ADDED are skipped.
Run from the repo root:  python3 tools/build-page-prompts.py"""
import re, glob
OUT = 'art/prompts/ch1-pages-all-with-dialogue.md'
MARK = '\n<!-- PAGES 11+ ARE GENERATED by tools/build-page-prompts.py from the storyboard. Do not edit by hand. -->\n'
NAME = {'JEFF':'Jeff','MEL':'Mel','HAL':'Hal','NIKKI':'Nikki','JARED':'Jared','DAN':'Dan','AGTA':'the Agta','MAMA':'Mama','PAPA':'Papa',
        'GAIL':'Gail','JANELLE':'Janelle','GAIL AND JANELLE':'Gail and Janelle together','DAD':"Jared's father",'SIR ARCHIE':'Sir Archie'}
def clean_note(t):
    keep = [x for x in re.split(r'(?<=[.!?])\s+', t) if not re.search(r'DRAFT|TO CONFIRM|to do|todo|optional beat', x, re.I)]
    return ' '.join(keep).strip()
def letter(line, last):
    m = re.match(r'CAPTION: "(.*)"$', line)
    if m: return 'caption box reads "%s"' % m.group(1), last
    m = re.match(r'SFX: "(.*)"$', line)
    if m: return 'sound effect lettering reads "%s"' % m.group(1), last
    m = re.match(r'Then, softly: "(.*)"$', line)
    if m: return 'a second, smaller speech bubble from %s reads "%s"' % (last, m.group(1)), last
    m = re.match(r'([A-Z][A-Z \']+?)(?: \(([^)]*)\))?: "(.*)"$', line)
    if not m: return None, last
    who = NAME.get(m.group(1), m.group(1).title()); how = (m.group(2) or '').lower(); txt = m.group(3)
    if 'thinking' in how: return 'thought bubble from %s reads "%s"' % (who, txt), who
    if 'memory' in how or 'downstairs' in how or 'kitchen' in how:
        return 'speech bubble with a jagged or wavy tail that points off panel, the speaker is NOT shown (%s, %s), reads "%s"' % (who, how, txt), who
    if how: return 'speech bubble from %s (%s) reads "%s"' % (who, how, txt), who
    return 'speech bubble from %s reads "%s"' % (who, txt), who
def convert(block):
    lines = [l.rstrip() for l in block.strip().split('\n')]
    out = [lines[0]]; panels = []; cur = None; last = ''
    for l in lines[1:]:
        if l.startswith('Layout:'): out.append(l); continue
        m = re.match(r'\*\*(\d+)\. ([A-Z]+)\.\*\* (.*)', l)
        if m: cur = {'n': m.group(1), 'size': m.group(2).lower(), 'text': m.group(3), 'let': [], 'note': ''}; panels.append(cur); continue
        if not l.strip() or cur is None: continue
        if l.startswith('Art note:'): cur['note'] = clean_note(l[9:].strip()); continue
        t, last = letter(l, last)
        if t: cur['let'].append(t)
        else: cur['text'] += ' ' + l.strip()
    for p in panels:
        s = 'Panel %s (%s): %s' % (p['n'], p['size'], p['text'])
        if p['let']: s += ' Lettering: ' + '; '.join(p['let']) + '.'
        if p['note']: s += ' Note: ' + p['note']
        out.append(''); out.append(s)
    return '\n'.join(out)
def main():
    blocks = {}
    for f in sorted(glob.glob('story-bible/chapter-1/pages-*.md')):
        t = open(f).read()
        for m in re.finditer(r'^## Page (\d+) .*?(?=^---|\Z)', t, re.S | re.M):
            n = int(m.group(1))
            if n >= 11 and 'TO BE ADDED' not in m.group(0): blocks[n] = convert(m.group(0))
    s = open(OUT).read()
    s = s.split(MARK)[0]
    s = re.sub(r'\n*Pages 11 to 50 of the old Butuan draft are archived.*\Z', '\n', s, flags=re.S).rstrip() + '\n'
    s += MARK + '\n' + '\n\n'.join(blocks[n] for n in sorted(blocks)) + '\n'
    open(OUT, 'w').write(s); print('pages written:', min(blocks), 'to', max(blocks), len(blocks))
if __name__ == '__main__': main()
